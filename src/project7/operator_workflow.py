    def reviewer_roles(self) -> dict[str, Any]:
        return json.loads(
            (
                self.repo_root
                / "config"
                / "profiles"
                / "icm_reviewer_roles.json"
            ).read_text(encoding="utf-8")
        )

    def record_disposition(
        self,
        *,
        reviewer_identity: str,
        reviewer_role_id: str,
        disposition: str,
        rationale: str,
        modified_conditions: list[str] | None = None,
        escalation_target_role_id: str | None = None,
    ) -> dict[str, Any]:
        self._require_stage("packet_ready")
        if self.stage != "packet_ready":
            raise OperatorWorkflowError(
                "A human disposition has already been recorded for this case."
            )

        from .human_disposition import record_human_disposition

        roles_config = self.reviewer_roles()
        role_by_id = {
            item["role_id"]: item
            for item in roles_config["roles"]
        }
        if reviewer_role_id not in role_by_id:
            raise OperatorWorkflowError(
                f"Unknown reviewer role: {reviewer_role_id}"
            )

        case_state = json.loads(
            (
                self.output_dir
                / "05_decision_support_packet"
                / "updated_case_state.json"
            ).read_text(encoding="utf-8")
        )
        recommendation = case_state["recommendation"]
        reviewer_role = role_by_id[reviewer_role_id]
        reviewer = {
            "role_id": reviewer_role["role_id"],
            "role_name": reviewer_role["role_name"],
            "organization_id": roles_config["organization_id"],
        }
        decided_at = utc_now()
        case_suffix = case_state["case_id"].replace("CASE-", "")
        response: dict[str, Any] = {
            "disposition_schema_version": "1.0.0",
            "disposition_id": f"DISP-{case_suffix}-OPERATOR",
            "case_id": case_state["case_id"],
            "recommendation_id": recommendation["recommendation_id"],
            "reviewer": reviewer,
            "disposition": disposition,
            "rationale": rationale.strip(),
            "modified_conditions": list(modified_conditions or []),
            "decided_at": decided_at,
        }
        if disposition == "escalate":
            if escalation_target_role_id not in role_by_id:
                raise OperatorWorkflowError(
                    "Escalation requires a valid configured target role."
                )
            target = role_by_id[escalation_target_role_id]
            response["escalated_to"] = {
                "role_id": target["role_id"],
                "role_name": target["role_name"],
                "organization_id": roles_config["organization_id"],
            }

        output = self.output_dir / "06_human_disposition"
        audit_path = self.audit_dir / "06_human_disposition_event.jsonl"
        result = record_human_disposition(
            repo_root=self.repo_root,
            case_state_path=(
                self.output_dir
                / "05_decision_support_packet"
                / "updated_case_state.json"
            ),
            human_response=response,
            reviewer_identity=reviewer_identity,
            reviewer_roles_path=(
                self.repo_root
                / "config"
                / "profiles"
                / "icm_reviewer_roles.json"
            ),
            prior_audit_path=self.audit_dir / "05_packet_events.jsonl",
            output_directory=output,
            audit_output_path=audit_path,
        )
        self._set_stage("human_disposition_recorded")
        return result

    def current_case_state_path(self) -> Path | None:
        candidates = [
            self.output_dir / "06_human_disposition" / "updated_case_state.json",
            self.output_dir / "05_decision_support_packet" / "updated_case_state.json",
            self.output_dir / "04_evidence_workflow" / "updated_case_state.json",
            self.output_dir / "03_clause_triage" / "updated_case_state.json",
            self.output_dir / "02_alignment_history" / "updated_case_state.json",
            self.output_dir / "01_intake" / "initial_case_state.json",
        ]
        return next((path for path in candidates if path.is_file()), None)

    def status_summary(self) -> dict[str, Any]:
        state_path = self.current_case_state_path()
        case_state = (
            json.loads(state_path.read_text(encoding="utf-8"))
            if state_path is not None
            else None
        )
        manifest = self._manifest()
        return {
            "operator_stage": manifest["stage"],
            "case_id": manifest.get("case_id"),
            "case_status": (
                case_state.get("case_status")
                if isinstance(case_state, dict)
                else None
            ),
            "human_disposition": (
                case_state.get("human_disposition")
                if isinstance(case_state, dict)
                else None
            ),
            "workspace_root": str(self.workspace_root),
        }

    def _bundle_inventory(self) -> list[dict[str, Any]]:
        items: list[dict[str, Any]] = []
        for path in sorted(self.workspace_root.rglob("*")):
            if not path.is_file():
                continue
            if path.name == "case_bundle_manifest.json":
                continue
            items.append(
                {
                    "path": path.relative_to(self.workspace_root).as_posix(),
                    "bytes": path.stat().st_size,
                    "sha256": sha256_file(path),
                }
            )
        return items

    def export_case_bundle(self, bundle_path: Path) -> Path:
        inventory = self._bundle_inventory()
        bundle_manifest = {
            "case_bundle_version": "1.0.0",
            "created_at": utc_now(),
            "operator_manifest": self._manifest(),
            "file_count": len(inventory),
            "files": inventory,
        }
        manifest_path = self.workspace_root / "case_bundle_manifest.json"
        manifest_path.write_text(
            json.dumps(bundle_manifest, indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )

        bundle_path = Path(bundle_path).resolve()
        bundle_path.parent.mkdir(parents=True, exist_ok=True)
        if bundle_path.exists():
            bundle_path.unlink()
        with zipfile.ZipFile(
            bundle_path,
            "w",
            compression=zipfile.ZIP_DEFLATED,
        ) as archive:
            for path in sorted(self.workspace_root.rglob("*")):
                if path.is_file():
                    archive.write(
                        path,
                        arcname=path.relative_to(self.workspace_root).as_posix(),
                    )
        return bundle_path

    @classmethod
    def restore_case_bundle(
        cls,
        *,
        repo_root: Path,
        bundle_path: Path,
        destination_root: Path,
    ) -> "OperatorWorkflow":
        bundle_path = Path(bundle_path).resolve()
        destination_root = Path(destination_root).resolve()
        if destination_root.exists():
            if any(destination_root.iterdir()):
                raise OperatorWorkflowError(
                    "Restore destination must be empty."
                )
        else:
            destination_root.mkdir(parents=True, exist_ok=True)

        with zipfile.ZipFile(bundle_path, "r") as archive:
            for member in archive.infolist():
                candidate = (destination_root / member.filename).resolve()
                if destination_root not in candidate.parents and candidate != destination_root:
                    raise OperatorWorkflowError(
                        "Unsafe path detected in case bundle."
                    )
            archive.extractall(destination_root)

        bundle_manifest_path = destination_root / "case_bundle_manifest.json"
        if not bundle_manifest_path.is_file():
            raise OperatorWorkflowError(
                "Case bundle manifest is missing."
            )
        bundle_manifest = json.loads(
            bundle_manifest_path.read_text(encoding="utf-8")
        )
        for item in bundle_manifest["files"]:
            path = destination_root / item["path"]
            if not path.is_file():
                raise OperatorWorkflowError(
                    f"Case bundle file is missing: {item['path']}"
                )
            if path.stat().st_size != item["bytes"]:
                raise OperatorWorkflowError(
                    f"Case bundle size mismatch: {item['path']}"
                )
            if sha256_file(path) != item["sha256"]:
                raise OperatorWorkflowError(
                    f"Case bundle checksum mismatch: {item['path']}"
                )

        return cls(
            repo_root=repo_root,
            workspace_root=destination_root,
        )
